//! The HTTP routes the daemon registers, with the token scope, payloads and a
//! summary of each. `interfaces/http/routes.txt` and `interfaces/http/openapi.json`
//! are generated from this table and the payload schemas.
//!
//! Scopes come from the handlers' own `claims.require` calls. A payload is typed
//! when the handler extracts or returns a concrete Rust type (or validates its
//! response against one with `checked`), and untyped when it uses `Json<Value>`.
//! `sdk` lists the type the TypeScript SDK declares for the same endpoint.

/// The token scope a route needs.
pub(crate) enum Scope {
    /// No token at all.
    None,
    /// Only the owner token; scoped tokens are refused.
    Owner,
    /// A token with this scope (the `admin` scope passes every check).
    One(&'static str),
    /// A token with every one of these scopes.
    All(&'static [&'static str]),
    /// The scope depends on the request.
    Depends {
        /// Scopes that are always needed.
        roles: &'static [&'static str],
        note: &'static str,
    },
}

/// A request, query or response payload.
pub(crate) enum Body {
    /// Nothing is read or sent.
    None,
    /// JSON the handler reads or builds as a `Value`.
    Untyped,
    /// JSON of this Rust type.
    Type(&'static str),
    /// An optional JSON body of this Rust type.
    Optional(&'static str),
    Multipart,
    /// Raw bytes with this content type.
    Bytes(&'static str),
    /// A server-sent event stream of this type.
    Sse(&'static str),
    /// A JSON page, or a server-sent event stream of this type when the
    /// request accepts `text/event-stream`.
    JsonOrSse(&'static str),
    /// A WebSocket upgrade for the named call socket.
    Upgrade(&'static str),
}

pub(crate) enum Idempotency {
    No,
    Required,
    Optional,
}

pub(crate) struct Route {
    pub(crate) method: &'static str,
    /// Path exactly as registered with the router.
    pub(crate) path: &'static str,
    /// Unique operation name, used as the OpenAPI operationId.
    pub(crate) id: &'static str,
    pub(crate) tag: &'static str,
    pub(crate) scope: Scope,
    pub(crate) idempotency: Idempotency,
    pub(crate) request: Body,
    pub(crate) query: Body,
    pub(crate) response: Body,
    /// Status of a successful response.
    pub(crate) status: u16,
    /// Types the TypeScript SDK declares for this endpoint, as (role, type)
    /// pairs where role is `request` or `response`.
    pub(crate) sdk: &'static [(&'static str, &'static str)],
    pub(crate) summary: &'static str,
}

