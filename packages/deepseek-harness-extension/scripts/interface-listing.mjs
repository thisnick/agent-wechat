#!/usr/bin/env node
// Writes interfaces/dsh/{tools,config}.txt from the built DSH plugin bundle.
// Usage: node scripts/interface-listing.mjs [--check]   (run `pnpm build` first)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = join(packageDir, '../..');
const outputDir = join(repoDir, 'interfaces/dsh');
const missing = 'MISSING DESCRIPTION';

const oneLine = text => String(text ?? '').split(/\s+/).filter(Boolean).join(' ');
const describe = text => oneLine(text) || missing;
const row = (item, attributes, doc) => `${item} | ${attributes.length ? attributes.join(', ') : '-'} | ${doc}`;
const literal = value => (typeof value === 'string' ? value : JSON.stringify(value));

/** Flattens a JSON schema into one row per property path (same format as the OpenClaw listing). */
export function schemaRows(prefix, schema, { required = false, path = '' } = {}) {
  const rows = [];
  const attributes = [];
  const branches = schema.anyOf ?? schema.oneOf ?? [];
  const types = [schema.type, ...branches.map(branch => branch.type)].flat().filter(Boolean);
  if (types.length) attributes.push([...new Set(types)].join('|'));
  if (required) attributes.push('required');
  if (schema.enum) attributes.push(`values ${schema.enum.map(literal).join('|')}`);
  if ('const' in schema) attributes.push(`const ${literal(schema.const)}`);
  for (const [key, label] of [['minimum', 'min'], ['maximum', 'max'], ['minLength', 'min length'], ['maxLength', 'max length'],
    ['minItems', 'min items'], ['maxItems', 'max items']]) {
    if (key in schema) attributes.push(`${label} ${literal(schema[key])}`);
  }
  if ('default' in schema) attributes.push(`default ${literal(schema.default)}`);
  if (prefix) rows.push(row(prefix, attributes, describe(schema.description)));
  const objects = [schema, ...branches];
  for (const object of objects) {
    const requiredKeys = new Set(object.required ?? []);
    for (const [key, child] of Object.entries(object.properties ?? {})) {
      rows.push(...schemaRows(prefix ? `${prefix}.${key}` : key, child, { required: requiredKeys.has(key), path: path ? `${path}.${key}` : key }));
    }
    if (object.additionalProperties && typeof object.additionalProperties === 'object') {
      rows.push(...schemaRows(`${prefix}.*`, object.additionalProperties, { path: `${path}.*` }));
    }
    if (object.items && typeof object.items === 'object' && (object.items.properties || object.items.anyOf || object.items.oneOf)) {
      rows.push(...schemaRows(`${prefix}[]`, object.items, { path: `${path}[]` }));
    }
  }
  return rows;
}

async function collect() {
  const plugin = await import(pathToFileURL(join(packageDir, 'dist/index.js')).href);
  if (typeof plugin.wechatToolCatalog !== 'function') throw new Error('dist/index.js does not export wechatToolCatalog; run pnpm build');
  if (!Array.isArray(plugin.dshConfigShape)) throw new Error('dist/index.js does not export dshConfigShape; run pnpm build');
  return { tools: plugin.wechatToolCatalog(), config: plugin.dshConfigShape };
}

export async function render() {
  const { tools, config } = await collect();
  const problems = [];
  const names = tools.map(tool => tool.name);
  if (new Set(names).size !== names.length) problems.push('duplicate tool names in the catalog');
  if (!names.length) problems.push('no tools listed');

  const toolRows = [];
  for (const tool of tools) {
    toolRows.push(row(`tool ${tool.name}`, [tool.visibility], describe(tool.description)));
    toolRows.push(...schemaRows(`tool ${tool.name}`, tool.parameters ?? {}).slice(1));
  }
  const configRows = config.map(entry => row(entry.path, [...entry.attributes], describe(entry.description)));

  const header = kind => `# DSH plugin ${kind}. Generated by packages/deepseek-harness-extension/scripts/interface-listing.mjs; do not edit.\n# Run \`pnpm interfaces\` after changing them. Format: ITEM | ATTRIBUTES | DESCRIPTION\n`;
  const file = (kind, rows) => `${header(kind)}${[...rows].sort().join('\n')}\n`;
  return { problems, files: { 'tools.txt': file('tools', toolRows), 'config.txt': file('config', configRows) } };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const { problems, files } = await render();
  if (problems.length) {
    console.error(`DSH plugin interface problems:\n${problems.map(problem => `- ${problem}`).join('\n')}`);
    process.exitCode = 1;
  }
  let stale = false;
  await mkdir(outputDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const path = join(outputDir, name);
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current.replaceAll('\r\n', '\n') === content) continue;
    if (check) { stale = true; console.error(`interfaces/dsh/${name} does not match the plugin. Run \`pnpm interfaces\`.`); }
    else await writeFile(path, content);
  }
  if (stale) process.exitCode = 1;
}
