#!/usr/bin/env node
// Writes interfaces/ui/routes.txt from the route table the UI itself routes with.
// Usage: node scripts/interface-listing.mjs [--check]
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = join(packageDir, '../..');
const outputDir = join(repoDir, 'interfaces/ui');
const missing = 'MISSING DESCRIPTION';

const oneLine = text => String(text ?? '').split(/\s+/).filter(Boolean).join(' ');
const row = (item, attributes, doc) => `${item} | ${attributes.length ? attributes.join(', ') : '-'} | ${oneLine(doc) || missing}`;

export async function render() {
  const { routeTable, routeParams } = await import(pathToFileURL(join(packageDir, 'src/routes.ts')).href);
  const problems = [];
  const rows = [];
  for (const entry of routeTable) {
    const params = routeParams(entry.pattern);
    if (new Set(params).size !== params.length) problems.push(`${entry.pattern} repeats a parameter`);
    rows.push(row(`route ${entry.pattern}`, params.length ? [`params ${params.join(', ')}`] : [], entry.description));
  }
  const items = rows.map(line => line.split(' | ')[0]);
  for (const item of new Set(items.filter((item, index) => items.indexOf(item) !== index)))
    problems.push(`${item} is listed twice`);
  const header = '# Desktop and web UI routes. Generated by packages/client-ui/scripts/interface-listing.mjs; do not edit.\n'
    + '# Run `pnpm interfaces` after changing them. Each address is `#` followed by the route. {server} is the hub\'s server ID, and\n'
    + '# {account}, {thread} and {message} are account, conversation and message IDs; each is URL-encoded.\n'
    + '# Format: ITEM | ATTRIBUTES | DESCRIPTION\n';
  return { problems, files: { 'routes.txt': `${header}${[...rows].sort().join('\n')}\n` } };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const { problems, files } = await render();
  if (problems.length) {
    console.error(`UI route problems:\n${problems.map(problem => `- ${problem}`).join('\n')}`);
    process.exitCode = 1;
  }
  let stale = false;
  await mkdir(outputDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const path = join(outputDir, name);
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current.replaceAll('\r\n', '\n') === content) continue;
    if (check) { stale = true; console.error(`interfaces/ui/${name} does not match the route table. Run \`pnpm interfaces\`.`); }
    else await writeFile(path, content);
  }
  if (stale) process.exitCode = 1;
}
