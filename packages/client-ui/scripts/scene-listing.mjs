#!/usr/bin/env node
// Writes interfaces/ui/scenes.txt from the scenes the visual review captures, so a
// change to what is reviewed shows up in the interface diff like a change to a route.
// Usage: node scripts/scene-listing.mjs [--check]
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = join(packageDir, '../..');
const outputDir = join(repoDir, 'interfaces/ui');
const missing = 'MISSING DESCRIPTION';

const oneLine = text => String(text ?? '').split(/\s+/).filter(Boolean).join(' ');

export async function render() {
  const { routeTable } = await import(pathToFileURL(join(packageDir, 'src/routes.ts')).href);
  const { scenes, viewports } = await import(pathToFileURL(join(packageDir, 'scenes/scenes.mjs')).href);
  const patterns = new Map(routeTable.map(entry => [entry.name, entry.pattern]));
  const problems = [];
  const rows = [];
  for (const scene of scenes) {
    const pattern = patterns.get(scene.route);
    if (!pattern) problems.push(`scene ${scene.name} opens unknown route ${scene.route}`);
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(scene.name)) problems.push(`scene name ${scene.name} must be lowercase words joined by hyphens`);
    const sizes = scene.viewports ?? [];
    if (!sizes.length || sizes.some(size => !(size in viewports)) || new Set(sizes).size !== sizes.length)
      problems.push(`scene ${scene.name} needs distinct viewports from ${Object.keys(viewports).join(', ')}`);
    const description = oneLine(scene.description);
    if (/[.!?]\s+\S/.test(description)) problems.push(`scene ${scene.name} should have a one-sentence description`);
    const ordered = Object.keys(viewports).filter(size => sizes.includes(size));
    rows.push(`scene ${scene.name} | route ${pattern ?? scene.route}, viewports ${ordered.join('+')} | ${description || missing}`);
  }
  const names = scenes.map(scene => scene.name);
  for (const name of new Set(names.filter((name, index) => names.indexOf(name) !== index))) problems.push(`scene ${name} is listed twice`);
  const header = '# UI scenes captured for visual review in CI and uploaded to Argos. Generated by packages/client-ui/scripts/scene-listing.mjs; do not edit.\n'
    + '# Run `pnpm --filter @agent-wechat/client-ui scenes:list` after changing them. A screenshot is named `<scene>@<viewport>`; viewports are\n'
    + '# `desktop` (1280x800) and `narrow` (390x844), joined by `+` when a scene has both. The route is the pattern the scene opens.\n'
    + '# Format: ITEM | ATTRIBUTES | DESCRIPTION\n';
  return { problems, files: { 'scenes.txt': `${header}${[...rows].sort().join('\n')}\n` } };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const { problems, files } = await render();
  if (problems.length) {
    console.error(`UI scene problems:\n${problems.map(problem => `- ${problem}`).join('\n')}`);
    process.exitCode = 1;
  }
  let stale = false;
  await mkdir(outputDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const path = join(outputDir, name);
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current.replaceAll('\r\n', '\n') === content) continue;
    if (check) { stale = true; console.error(`interfaces/ui/${name} does not match the scenes. Run \`pnpm --filter @agent-wechat/client-ui scenes:list\`.`); }
    else await writeFile(path, content);
  }
  if (stale) process.exitCode = 1;
}
